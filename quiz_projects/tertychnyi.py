

questions = [
    ("1. Столиця Франції?", "париж"),
    ("2. Скільки буде 5 * 6?", "30"),
    ("3. Яка планета є третьою від Сонця?", "земля"),
    ("4. Хто написав 'Кобзар'?", "шевченко"),
    ("5. Скільки днів у тижні?", "7"),
    ("6. Яка мова є державною в Україні?", "українська"),
    ("7. Який океан найбільший?", "тихий"),
    ("8. Найменший континент?", "австралія"),
    ("9. Скільки градусів у прямому куті?", "90"),
    ("10. Хто винайшов лампу?", "едісон"),
    ("11. Яка столиця України?", "київ"),
    ("12. Який колір утворюється при змішуванні жовтого та синього?", "зелений")
]

score = 0

print("=== ТЕСТ З 12 ПИТАНЬ ===\n")

for q, correct in questions:
    answer = input(q + " ").strip().lower()
    if answer == correct:
        score += 1
        print("✔ Правильно!\n")
    else:
        print(f"✘ Неправильно. Правильна відповідь: {correct}\n")

print(f"Ваш результат: {score} з {len(questions)} балів.")

if score == 12:
    print("Відмінно! 🔥")
elif score >= 8:
    print("Добрий результат! 🙂")
else:
    print("Потрібно трохи потренуватися 😅")
